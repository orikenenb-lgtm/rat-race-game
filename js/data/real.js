// ---------- helpers (pure, deterministic) ----------
// A month can be given as 'YYYY-MM', 'YYYY-MM-DD' (interpolates inside the month) or as an absolute
// month number (year*12 + month-1, may be fractional). Dates outside a series clamp to its first/last value.
function monthNum(ym) {
  if (typeof ym === 'number') return ym;
  const m = /^(\d{4})-(\d{2})(?:-(\d{2}))?$/.exec(String(ym));
  if (!m) return NaN;
  const y = +m[1], mo = +m[2];
  let n = y * 12 + (mo - 1);
  if (m[3]) n += (+m[3] - 1) / new Date(Date.UTC(y, mo, 0)).getUTCDate();
  return n;
}
export function ymAdd(ym, k) {
  const n = Math.floor(monthNum(ym)) + k;
  return `${Math.floor(n / 12)}-${String((n % 12) + 1).padStart(2, '0')}`;
}
export function seriesAt(name, ym) {
  const s = SERIES[name];
  if (!s) return null;
  const i = monthNum(ym) - monthNum(s.start);
  const v = s.values;
  if (!(i > 0)) return v[0];            // also catches NaN
  if (i >= v.length - 1) return v[v.length - 1];
  const lo = Math.floor(i), f = i - lo;
  return f ? v[lo] + (v[lo + 1] - v[lo]) * f : v[lo];
}
export function monthlyChange(name, ym) { // ratio vs previous month (1 = unchanged)
  const n = monthNum(ym);
  const prev = seriesAt(name, n - 1);
  return prev ? seriesAt(name, n) / prev : 1;
}
