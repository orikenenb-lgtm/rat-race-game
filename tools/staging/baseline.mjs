#!/usr/bin/env node
// tools/staging/baseline.mjs — print supabase/schema/production_baseline.sql as an applicable script (stdout).
// The baseline is a catalog dump (tables alphabetically, then functions); this orders the tables by foreign key exactly like the
// PGlite loader of tests/sql_drafts.test.mjs / online_migration.test.mjs, so the local PostgreSQL gets the same schema.
//   node tools/staging/baseline.mjs [<src root>] | psql …
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = process.argv[2] || join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const sql = readFileSync(join(root, 'supabase/schema/production_baseline.sql'), 'utf8');
const blocks = sql.split(/\n(?=create table |CREATE OR REPLACE FUNCTION )/);
const tables = {}; const funcs = [];
for (const b of blocks) {
  const m = /^create table game\.(\w+)/.exec(b);
  if (m) tables[m[1]] = b; else if (b.startsWith('CREATE OR REPLACE FUNCTION')) funcs.push(b.replace(/\n--[^\n]*/g, ''));
}
const order = ['players', 'groups', 'group_members', 'challenges', 'results', 'events', 'energy_gifts', 'admins', 'admin_setup'];
const missing = Object.keys(tables).filter((t) => !order.includes(t));
if (missing.length) { console.error('baseline.mjs: unknown tables (add them to the FK order): ' + missing.join(', ')); process.exit(1); }
const out = ['-- generated by tools/staging/baseline.mjs from supabase/schema/production_baseline.sql', 'begin;', 'create sequence if not exists game.events_id_seq;'];
for (const t of order) out.push(tables[t].trim());
for (const f of funcs) out.push(f.trim().replace(/;?\s*$/, ';'));
out.push('commit;');
process.stdout.write(out.join('\n\n') + '\n');
